ALTER ROLE postgres PASSWORD NULL;
CREATE ROLE demo_owner NOLOGIN;
CREATE ROLE app1 LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS PASSWORD NULL;
CREATE ROLE app2 LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS PASSWORD NULL;
REVOKE ALL ON DATABASE productdb FROM PUBLIC;
GRANT CONNECT ON DATABASE productdb TO app1, app2;
REVOKE ALL ON SCHEMA public FROM PUBLIC;
CREATE SCHEMA app1 AUTHORIZATION demo_owner;
CREATE SCHEMA app2 AUTHORIZATION demo_owner;
SET ROLE demo_owner;
CREATE TABLE app1.notes (id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY, body text NOT NULL, created_at timestamptz NOT NULL DEFAULT now());
CREATE TABLE app2.notes (id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY, body text NOT NULL, created_at timestamptz NOT NULL DEFAULT now());
INSERT INTO app1.notes(body) VALUES ('Only App 1 can read this note.');
INSERT INTO app2.notes(body) VALUES ('Only App 2 can read this note.');
RESET ROLE;
GRANT USAGE ON SCHEMA app1 TO app1;
GRANT USAGE ON SCHEMA app2 TO app2;
GRANT SELECT, INSERT ON app1.notes TO app1;
GRANT SELECT, INSERT ON app2.notes TO app2;
GRANT USAGE ON ALL SEQUENCES IN SCHEMA app1 TO app1;
GRANT USAGE ON ALL SEQUENCES IN SCHEMA app2 TO app2;
ALTER ROLE app1 SET statement_timeout = '5s';
ALTER ROLE app2 SET statement_timeout = '5s';
